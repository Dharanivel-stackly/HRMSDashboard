export const mockCalendarDays: CalendarDay[] = (() => {
  const days: CalendarDay[] = []
  for (let d = 1; d <= 31; d++) {
    const date = `2026-08-${String(d).padStart(2, '0')}`
    const weekday = new Date(date).getDay()
    if (weekday === 0 || weekday === 6) {
      days.push({ date, status: 'week_off' })
    } else if (d === 15) {
      days.push({ date, status: 'holiday' })
    } else if (d === 12) {
      days.push({ date, status: 'on_leave' })
    } else if (d === 8) {
      days.push({ date, status: 'absent' })
    } else if (d === 5 || d === 19) {
      days.push({
        date,
        status: 'late',
        checkIn: '09:35',
        checkOut: '18:00',
        workHours: 7.9,
      })
    } else if (d === 24) {
      days.push({
        date,
        status: 'correction_pending',
        checkIn: '10:15',
        checkOut: '18:00',
        workHours: 7.2,
      })
    } else if (d <= 25) {
      days.push({
        date,
        status: 'present',
        checkIn: '09:02',
        checkOut: '18:10',
        workHours: 8.5,
      })
    } else {
      days.push({ date, status: null })
    }
  }
  return days
})()

